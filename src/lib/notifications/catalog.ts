function t(
  key: string,
  category: TemplateCategory,
  name: string,
  subject: string,
  previewText: string,
  heading: string,
  body: string[],
  cta?: { ctaLabel: string; ctaUrl: string },
  extra?: { secondaryLabel?: string; secondaryUrl?: string },
): TemplateDefinition {
  const used = new Set<string>();
  for (const chunk of [subject, previewText, heading, ...body, cta?.ctaUrl ?? ""]) {
    for (const m of chunk.matchAll(/\{\{(\w+)\}\}/g)) used.add(m[1]);
  }
  return {
    key,
    category,
    channel: "email",
    locale: "pt-PT",
    name,
    subject,
    previewText,
    heading,
    body,
    variables: [...used],
    version: 1,
    ...cta,
    ...extra,
  };
}

